async def test_filter_by_update_time(live_c8y: CumulocityClient, session_device, sample_alarms: List[Alarm]):
    """Verify that filtering by lastUpdatedTime works as expected."""

    alarm = sample_alarms[0]

    # created alarms should all have different update times
    # -> we use the middle/pivot element for queries
    update_datetimes = [a.update_datetime for a in sample_alarms]
    update_datetimes.sort()
    pivot = update_datetimes[len(update_datetimes)//2]

    # Note: We are using additional status/severity so that we don't interfere
    # with other tests creating alarms for the same device
    before_alarms = await live_c8y.alarms.get_all(source=alarm.source, updated_before=pivot,
                                            severity=alarm.severity, status=alarm.status)
    after_alarms = await live_c8y.alarms.get_all(source=alarm.source, updated_after=pivot,
                                           severity=alarm.severity, status=alarm.status)

    # -> selected alarms should match the update times from 'before'
    # upper boundary, i.e. before/to timestamp is exclusive -> does not include pivot
    before_datetimes = list(filter(lambda x: x < pivot, update_datetimes))
    result_datetimes = [a.update_datetime for a in before_alarms]
    assert sorted(result_datetimes) == sorted(before_datetimes)

    # -> selected alarms should match the update times from 'after'
    # lower boundary, i.e. after/from timestamp is inclusive -> includes pivot
    after_datetimes = list(filter(lambda x: x >= pivot, update_datetimes))
    result_datetimes = [a.update_datetime for a in after_alarms]
    assert sorted(result_datetimes) == sorted(after_datetimes)


async def test_client_side_filtering(live_c8y: CumulocityClient, sample_alarms: List[Alarm]):
    """Verify that client-side filtering works as expected."""
    alarm = random.choice(sample_alarms)

    alarms_1 = await live_c8y.alarms.get_all(source=alarm.source)
    # we need _some_ start date, otherwise the result set would be too big
    created_after = alarm.creation_datetime - datetime.timedelta(hours=1)
    # not that the filter uses source.id as this is raw JSON format
    alarms_2 = await live_c8y.alarms.get_all(created_after=created_after, include=f"source.id == '{alarm.source}'")
    assert len(alarms_1) == len(alarms_2)
