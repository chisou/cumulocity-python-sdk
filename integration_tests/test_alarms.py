async def test_CRUD(live_c8y: CumulocityClient, session_device: Device):  # noqa (case)
    """Verify that basic CRUD functionality works."""

    typename = create_random_name()
    alarm = Alarm(c8y=live_c8y, type=typename, text=f"{typename} text", source=session_device.id,
                  time="now", severity=AlarmSeverity.MAJOR)

    created_alarm = await alarm.create()
    try:
        # 1) assert correct creation
        assert created_alarm.id
        assert created_alarm.type == typename
        assert typename in created_alarm.text
        assert created_alarm.status == AlarmStatus.ACTIVE  # auto generated by Cumulocity
        assert created_alarm.count  # auto generated by Cumulocity
        assert created_alarm.time  # auto generated by API
        assert created_alarm.creation_time  # auto generated by Cumulocity

        # 2) update updatable fields
        created_alarm.text = f"{typename} updated"
        created_alarm.severity = AlarmSeverity.MINOR
        created_alarm.status = AlarmStatus.ACKNOWLEDGED

        updated_alarm = await created_alarm.update(copy=True)
        # -> text should be updated in db
        assert updated_alarm.text == created_alarm.text
        assert updated_alarm.status == created_alarm.status
        assert updated_alarm.severity == created_alarm.severity

        # 3) use apply_to
        model_alarm = Alarm(c8y=live_c8y, text="some text", custom_attribute="value")
        await model_alarm.apply_to(created_alarm.id)
        # -> text should be updated in db
        updated_alarm = await live_c8y.alarms.get(created_alarm.id)
        assert updated_alarm.text == "some text"
        assert updated_alarm["custom_attribute"] == "value"

        # 4) reload should reflect the same state
        reloaded_alarm = await updated_alarm.reload(copy=True)
        assert reloaded_alarm.text == updated_alarm.text
        assert reloaded_alarm["custom_attribute"] == "value"

    finally:
        await created_alarm.delete()

    # 5) assert deletion
    with pytest.raises(KeyError) as e:
        await live_c8y.alarms.get(created_alarm.id)
    assert created_alarm.id in str(e)


async def test_CRUD_2(live_c8y: CumulocityClient, session_device: Device):  # noqa (case)
    """Verify that basic CRUD functionality via the API works."""

    typename = create_random_name()
    time = "1970-01-01T11:22:33Z"
    alarm1 = Alarm(c8y=live_c8y, type=typename + "_1", text=f"{typename} text", source=session_device.id,
                   time=time, severity=AlarmSeverity.MINOR)
    alarm2 = Alarm(c8y=live_c8y, type=typename + "_2", text=f"{typename} text", source=session_device.id,
                   time=time, severity=AlarmSeverity.MINOR)

    # 1) create multiple events and read from Cumulocity
    await live_c8y.alarms.create(alarm1, alarm2)
    get_filter = {"source": session_device.id,
                  "before": "1970-01-02",
                  "after": "1970-01-01"}

    # -> we should have exactly 2 alarms of this type
    alarms = await live_c8y.alarms.get_all(**get_filter)
    alarm_ids = [e.id for e in alarms]
    assert len(alarms) == 2

    try:
        # 2) update updatable fields
        for alarm in alarms:
            alarm.text = "new text"
            alarm.severity = AlarmSeverity.MAJOR
            alarm.status = AlarmStatus.ACKNOWLEDGED
        await live_c8y.alarms.update(*alarms)

        # -> still just 2 alarms, but with updated fields
        alarms = await live_c8y.alarms.get_all(**get_filter)
        assert len(alarms) == 2
        for alarm in alarms:
            assert alarm.text == "new text"
            assert alarm.severity == AlarmSeverity.MAJOR
            assert alarm.status == AlarmStatus.ACKNOWLEDGED

        # 5) apply mode updates
        model = Alarm(text="another update", simple_attribute="value")
        await live_c8y.alarms.apply_to(model, *alarm_ids)

        # -> the new text should be in all events
        alarms = await live_c8y.alarms.get_all(**get_filter)
        assert len(alarms) == 2
        assert all(a.text == "another update" for a in alarms)
        assert all(a["simple_attribute"] == "value" for a in alarms)

        # 6) use apply_to with json
        await live_c8y.alarms.apply_to({"text": "new text", "add_info": "yes"}, *alarm_ids)

        # -> the new text should be in all events
        alarms = await live_c8y.alarms.get_all(**get_filter)
        assert len(alarms) == 2
        assert all(a.text == "new text" for a in alarms)
        assert all(a["add_info"] == "yes" for a in alarms)

    finally:
        await live_c8y.alarms.delete_by(**get_filter)

    # 6) assert deletion
    for attempt in Retrying(stop=stop_after_attempt(3), wait=wait_exponential(multiplier=0.5), reraise=True):
        with attempt:
            assert not await live_c8y.alarms.get_all(**get_filter)


