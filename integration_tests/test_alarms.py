async def test_apply_by(live_c8y: CumulocityClient, session_device: Device):
    """Verify that the apply_by function works."""

    num_alarms = 5
    name = create_random_name()
    alarms = [await Alarm(live_c8y, type=f"{name}_{i}", text=f"{name} text", source=session_device.id,
                    time="2021-06-22T11:33:55Z", severity=AlarmSeverity.CRITICAL).create()
              for i in range(1, num_alarms+1)]
    alarm = alarms[0]
    model = Alarm(status=AlarmStatus.ACKNOWLEDGED)

    filter_kwargs = {"source": alarm.source,
                     "severity": alarm.severity,
                     "before": "2022-01-01",
                     "after": "2020-12-31"}

    # 1) apply model change by query
    await live_c8y.alarms.apply_by(model, **filter_kwargs)

    # -> all matching objects should have been updated
    alarms = await live_c8y.alarms.get_all(**filter_kwargs)
    assert len(alarms) == num_alarms
    assert all(a.status == model.status for a in alarms)


